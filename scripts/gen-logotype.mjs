#!/usr/bin/env node
// og-image のロゴタイプ "celestia" をアウトライン化して
// assets/icons/logotype.svg を生成する（結果はコミットする）。
//
//   node scripts/gen-logotype.mjs
//
// フォント: Cormorant Garamond Light (wght 300) — サイトの masthead と同一。
//           SIL Open Font License 1.1。フォントファイル自体はコミットせず、
//           初回実行時に Google Fonts から tools/.cache/ へダウンロードする。
// 組版:     font-size 104px / letter-spacing 0.42em（masthead の h1 と同じ比率）、
//           1200x630 キャンバスの x=600 中央、ベースライン y=520。
//
// build-icons.mjs はこの生成物（logotype.svg 内の <path>）を読み込むだけなので、
// 通常のビルドはフォント環境に一切依存しない。

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import opentype from 'opentype.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fontPath = path.join(root, 'tools', '.cache', 'CormorantGaramond-Light.ttf');
const outPath = path.join(root, 'assets', 'icons', 'logotype.svg');

// wght@300 静的インスタンス（css2 API https://fonts.googleapis.com/css2?family=Cormorant+Garamond:wght@300 が返す URL）
const FONT_URL =
  'https://fonts.gstatic.com/s/cormorantgaramond/v21/co3umX5slCNuHLi8bLeY9MK7whWMhyjypVO7abI26QOD_qE6GnM.ttf';

const TEXT = 'celestia';
const SIZE = 104;
const TRACKING = 0.42; // em
const CANVAS = { w: 1200, h: 630 };
const BASELINE = 520;

async function ensureFont() {
  if (existsSync(fontPath)) return;
  console.log(`  downloading ${FONT_URL}`);
  const res = await fetch(FONT_URL);
  if (!res.ok) throw new Error(`font download failed: ${res.status}`);
  await mkdir(path.dirname(fontPath), { recursive: true });
  await writeFile(fontPath, Buffer.from(await res.arrayBuffer()));
}

async function main() {
  await ensureFont();
  const font = opentype.parse((await readFile(fontPath)).buffer);
  const opts = { kerning: true, letterSpacing: TRACKING };

  // いったん x=0 で組んで実インク境界を取り、光学的にセンタリングする
  const probe = font.getPath(TEXT, 0, BASELINE, SIZE, opts);
  const bb = probe.getBoundingBox();
  const x0 = CANVAS.w / 2 - (bb.x1 + bb.x2) / 2;
  const d = font.getPath(TEXT, x0, BASELINE, SIZE, opts).toPathData(2);

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS.w} ${CANVAS.h}" width="${CANVAS.w}" height="${CANVAS.h}">
  <!-- generated by scripts/gen-logotype.mjs — DO NOT EDIT BY HAND
       font: Cormorant Garamond Light (OFL 1.1) / ${SIZE}px / tracking ${TRACKING}em / baseline y=${BASELINE} -->
  <path d="${d}" fill="#C9A227"/>
</svg>
`;
  await writeFile(outPath, svg);
  const fin = font.getPath(TEXT, x0, BASELINE, SIZE, opts).getBoundingBox();
  console.log(
    `  logotype.svg  ink x ${fin.x1.toFixed(1)}..${fin.x2.toFixed(1)} (center ${((fin.x1 + fin.x2) / 2).toFixed(1)}), y ${fin.y1.toFixed(1)}..${fin.y2.toFixed(1)}`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
