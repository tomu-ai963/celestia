/**
 * deltat.mjs — ΔT（TT − UT1）と、UT ⇄ TT の変換
 *
 * ■ なぜ要るか
 * 暦日から作るユリウス日は **UT**（世界時 = 地球の自転が決める時刻）だが、
 * 軌道理論（JPL近似要素・Meeus の月・歳差）の引数 T は **TT**（力学時 = 一様に進む時刻）
 * を前提にしている。両者の差 ΔT は地球の自転の遅れの累積で、
 *   1900年 −3秒 / 1950年 +29秒 / 2000年 +64秒 / 2050年 +93秒（予測）
 * ある。月は 0.55″/秒 動くので、2050年では **約 51″** の位置の違いになる。
 * P3 で月を ELP 完全版に差し替えて Horizons 比較 21.7″ まで詰めた時点で、
 * ΔT が月の精度を支配する最大の要因になった。
 *
 * ■ どこに適用するか（適用先を間違えると桁違いにずれる）
 *   軌道理論の引数 T（helio / moonPos / 交点 / リリス）  → **TT**
 *   歳差回転量                                          → TT（UTとの差は 0.001″ 未満だが統一）
 *   GMST / 地方恒星時（地平線・天頂ベクトル）           → **UT**
 * GMST は「UT の関数」として定義されている量なので、ここに TT を渡すと
 * 64秒 × 15.041″/秒 ≒ **963″ = 0.27°** 地平線が回ってしまう。
 * astro.mjs 側は変数名を jdUT / jdTT で分け、tests/deltat.test.mjs が回帰を見張る。
 *
 * ■ 実装の構成 — 観測値のテーブル + 多項式
 *
 * 骨格は Espenak–Meeus の区分多項式（外部データ不要・−1999〜+3000 を1本で覆う）。
 * ただし **2005年以降の区間は当てにならない**。この区間は 2006年ごろに過去の傾向から
 * 外挿して作られたもので、その後に地球の自転がむしろ速まったため、
 * 実測とずれていく（本実装の測定で 2020年: 多項式 71.60秒 / 実測 69.36秒 = +2.24秒、
 * 2026年では +5.96秒）。
 *
 * そこで **1973–2026 は USNO/IERS の観測値を年1点で持ち、外側を多項式で補う**構成にした。
 * テーブルを持つ側に倒した理由:
 *   - 出生日は 20〜21世紀に集中する。アプリの主用途がまさに多項式の外挿区間に当たる
 *   - 54個の数値（約 400 バイト）で済み、外部依存もフェッチも増えない
 *   - 値が実測である以上「推測で書いた数値はない」という本リポジトリの方針に合う
 * 逆に多項式1本にしなかったのは、2.2秒（月で 1.2″）を捨てる合理的な理由が
 * 「コードが数行短い」しかないため。1800–1972 は多項式が当時の観測に対して
 * フィットされたものなので、そのまま使って差し支えない
 * （実測: 1973年で多項式 43.31秒 / テーブル 43.37秒 = 0.06秒差）。
 *
 * ■ 継ぎ目を跳ばせない
 * テーブルと多項式をそのまま貼り合わせると 2026年で 5.96秒の段差ができる。
 * このアプリは時間軸を連続にスクラブするので、段差はそのまま月が 3.3″ 飛ぶ
 * 不連続として見えてしまう。そこで **境界での差を「補正量」として持ち、
 * 外側へ向かって線形に 0 へ落とす**。
 *   前方: 2026 → 2050 で 0 に（2050 は Espenak–Meeus の当該区間の終端でもあり、
 *         アプリの対応上限でもある。そこから先は多項式だけが唯一の手がかりになる）
 *   後方: 1973 → 1963 で 0 に（差は 0.06秒しかないが、扱いを揃えておく）
 * ΔT は全域で連続になり、2050年では多項式そのままの 93.0秒に戻る。
 *
 * 一次資料:
 *   Espenak & Meeus, "Polynomial Expressions for Delta T"
 *     https://eclipse.gsfc.nasa.gov/SEcat5/deltatpoly.html （NASA/GSFC, パブリックドメイン）
 *   観測値 ΔT = TT − UT1: USNO EO "deltat.data"（各年1月1日の値）
 *     https://maia.usno.navy.mil/ser7/deltat.data / https://maia.usno.navy.mil/products/deltaT
 *     IERS の (UT1−UTC) と閏秒から作られた公表値。米国政府作成でパブリックドメイン
 */

/** ユリウス日 → 十進年。ΔT は年の関数なのでこれで足りる（グレゴリオ暦年） */
export const jdToDecimalYear = jd => 2000 + (jd - 2451545.0) / 365.2425;

/**
 * ΔT の観測値（秒）。各年 **1月1日** の値。出典は USNO deltat.data。
 * 2020年の 69.3612 を頂点に、2021年以降はわずかに減っている
 * （地球の自転が速まっているため）。多項式は単調増加なのでこの反転を表現できない。
 */
const OBS_Y0 = 1973;
const OBS = [
  43.3724, 44.4841, 45.4761, 46.4567, 47.5214, 48.5344, 49.5861, 50.5387, 51.3808, 52.1668,
  52.9565, 53.7882, 54.3427, 54.8713, 55.3222, 55.8197, 56.3000, 56.8553, 57.5653, 58.3092,
  59.1218, 59.9845, 60.7853, 61.6287, 62.2950, 62.9659, 63.4673, 63.8285, 64.0908, 64.2998,
  64.4734, 64.5736, 64.6876, 64.8452, 65.1464, 65.4573, 65.7768, 66.0699, 66.3246, 66.6030,
  66.9069, 67.2810, 67.6439, 68.1024, 68.5927, 68.9676, 69.2202, 69.3612, 69.3594, 69.2945,
  69.2039, 69.1752, 69.1377, 69.1099
];
const OBS_Y1 = OBS_Y0 + OBS.length - 1;   // 2026

/** 補正量を 0 へ落とす窓（年）。前方の終端 2050 は多項式の区間終端とアプリの上限 */
const FADE_FORWARD_TO = 2050;
const FADE_BACKWARD = 10;

/** 昇冪の係数配列で多項式を評価 */
const poly = (t, c) => c.reduceRight((s, k) => s * t + k, 0);

/**
 * Espenak–Meeus の区分多項式（秒）。有効範囲は −1999〜+3000。係数は原典のまま。
 *
 * 区間の切れ目は厳密には連続しない（区間ごとに独立にフィットされているため）。
 * 実測した段差は 1800年で 0.04秒、1900年で 0.09秒、最大でも 1600年の 0.25秒。
 * 月にして 0.05″ 程度なので、上の継ぎ目補正のように埋めることはせず原典どおりにした。
 */
export function espenakMeeus(y) {
  let t, u;
  if (y < -500) { u = (y - 1820) / 100; return -20 + 32 * u * u; }
  if (y < 500) {
    u = y / 100;
    return poly(u, [10583.6, -1014.41, 33.78311, -5.952053,
      -0.1798452, 0.022174192, 0.0090316521]);
  }
  if (y < 1600) {
    u = (y - 1000) / 100;
    return poly(u, [1574.2, -556.01, 71.23472, 0.319781,
      -0.8503463, -0.005050998, 0.0083572073]);
  }
  if (y < 1700) { t = y - 1600; return poly(t, [120, -0.9808, -0.01532, 1 / 7129]); }
  if (y < 1800) {
    t = y - 1700;
    return poly(t, [8.83, 0.1603, -0.0059285, 0.00013336, -1 / 1174000]);
  }
  if (y < 1860) {
    t = y - 1800;
    return poly(t, [13.72, -0.332447, 0.0068612, 0.0041116, -0.00037436,
      0.0000121272, -0.0000001699, 0.000000000875]);
  }
  if (y < 1900) {
    t = y - 1860;
    return poly(t, [7.62, 0.5737, -0.251754, 0.01680668, -0.0004473624, 1 / 233174]);
  }
  if (y < 1920) {
    t = y - 1900;
    return poly(t, [-2.79, 1.494119, -0.0598939, 0.0061966, -0.000197]);
  }
  if (y < 1941) { t = y - 1920; return poly(t, [21.20, 0.84493, -0.076100, 0.0020936]); }
  if (y < 1961) { t = y - 1950; return poly(t, [29.07, 0.407, -1 / 233, 1 / 2547]); }
  if (y < 1986) { t = y - 1975; return poly(t, [45.45, 1.067, -1 / 260, -1 / 718]); }
  if (y < 2005) {
    t = y - 2000;
    return poly(t, [63.86, 0.3345, -0.060374, 0.0017275, 0.000651814, 0.00002373599]);
  }
  if (y < 2050) { t = y - 2000; return poly(t, [62.92, 0.32217, 0.005589]); }
  if (y < 2150) { u = (y - 1820) / 100; return -20 + 32 * u * u - 0.5628 * (2150 - y); }
  u = (y - 1820) / 100;
  return -20 + 32 * u * u;
}

/** テーブルの線形補間（年1点なので年内は直線） */
function observed(y) {
  const i = Math.min(OBS.length - 2, Math.max(0, Math.floor(y) - OBS_Y0));
  const f = y - (OBS_Y0 + i);
  return OBS[i] + (OBS[i + 1] - OBS[i]) * f;
}

/** 継ぎ目での「観測値 − 多項式」。モジュール読み込み時に自分で測る（手打ちしない） */
const GAP_LO = OBS[0] - espenakMeeus(OBS_Y0);                    // 実測 +0.06 秒
const GAP_HI = OBS[OBS.length - 1] - espenakMeeus(OBS_Y1);       // 実測 −5.96 秒

/** 十進年 → ΔT（秒）。テーブル区間は観測値、外側は多項式 + 減衰する継ぎ目補正 */
export function deltaTAtYear(y) {
  if (y >= OBS_Y0 && y <= OBS_Y1) return observed(y);
  const p = espenakMeeus(y);
  if (y < OBS_Y0) {
    return p + GAP_LO * Math.max(0, 1 - (OBS_Y0 - y) / FADE_BACKWARD);
  }
  return p + GAP_HI * Math.max(0, 1 - (y - OBS_Y1) / (FADE_FORWARD_TO - OBS_Y1));
}

/**
 * ΔT（秒）。引数の JD は UT でも TT でもよい —
 * 両者の差は最大でも 100秒 ≒ 3e−6 年で、ΔT の年変化率（最大 1.5秒/年）を
 * 掛けても 5e−6 秒にしかならない。
 */
export const deltaTSeconds = jd => deltaTAtYear(jdToDecimalYear(jd));

/** ΔT（日）。JD にそのまま足し引きできる形 */
export const deltaTDays = jd => deltaTSeconds(jd) / 86400;

/** UT のユリウス日 → TT のユリウス日（軌道理論・歳差へ渡す側） */
export const utToTT = jdUT => jdUT + deltaTDays(jdUT);

/** TT のユリウス日 → UT のユリウス日（utToTT の逆。上記の理由で反復は不要） */
export const ttToUT = jdTT => jdTT - deltaTDays(jdTT);
