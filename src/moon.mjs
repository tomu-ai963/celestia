/** 月の基本引数（度）。Meeus 47.1–47.6 */
export function moonArgs(T) {
  const T2 = T * T, T3 = T2 * T, T4 = T3 * T;
  return {
    Lp: norm(218.3164477 + 481267.88123421 * T - 0.0015786 * T2 + T3 / 538841 - T4 / 65194000),
    D:  norm(297.8501921 + 445267.1114034 * T - 0.0018819 * T2 + T3 / 545868 - T4 / 113065000),
    M:  norm(357.5291092 + 35999.0502909 * T - 0.0001536 * T2 + T3 / 24490000),
    Mp: norm(134.9633964 + 477198.8675055 * T + 0.0087414 * T2 + T3 / 69699 - T4 / 14712000),
    F:  norm(93.2720950 + 483202.0175233 * T - 0.0036539 * T2 - T3 / 3526000 + T4 / 863310000)
  };
}

/**
 * Meeus 完全版。戻り値は of-date の黄経・黄緯（度）と地心距離（AU）、
 * および黄道直交ベクトル。
 */
export function moonPos(T) {
  const { Lp, D, M, Mp, F } = moonArgs(T);
  // 地球軌道離心率の永年変化。M を含む項に e（|M|=2 なら e²）を掛ける
  const e = 1 - 0.002516 * T - 0.0000074 * T * T, e2 = e * e;
  const A1 = norm(119.75 + 131.849 * T);
  const A2 = norm(53.09 + 479264.290 * T);
  const A3 = norm(313.45 + 481266.484 * T);

  // 金星・木星の摂動と地球の扁平による加算項（Meeus p.342）
  let sl = 3958 * sin(A1) + 1962 * sin(Lp - F) + 318 * sin(A2);
  let sr = 0;
  let sb = -2235 * sin(Lp) + 382 * sin(A3) + 175 * sin(A1 - F)
         + 175 * sin(A1 + F) + 127 * sin(Lp - Mp) - 115 * sin(Lp + Mp);

  for (const [d, m, mp, f, cl, cr] of TA) {
    const arg = d * D + m * M + mp * Mp + f * F;
    const k = m === 0 ? 1 : (m === 1 || m === -1) ? e : e2;
    sl += cl * sin(arg) * k;
    sr += cr * cos(arg) * k;
  }
  for (const [d, m, mp, f, cb] of TB) {
    const arg = d * D + m * M + mp * Mp + f * F;
    const k = m === 0 ? 1 : (m === 1 || m === -1) ? e : e2;
    sb += cb * sin(arg) * k;
  }

  const lon = norm(Lp + sl * 1e-6);
  const lat = sb * 1e-6;
  const distKm = 385000.56 + sr * 1e-3;
  return vec(lon, lat, distKm / AU);
}

/**
 * P2 までの短縮級数（黄経19項 / 黄緯9項 / 距離5項）。
 * 現役ではなく、moonPos との差を測るためだけに残している。
 */
export function moonPosShort(T) {
  const { Lp, D, M, Mp, F } = moonArgs(T);
  const l = Lp
   +6.288774*sin(Mp)      +1.274027*sin(2*D-Mp)   +0.658314*sin(2*D)
   +0.213618*sin(2*Mp)    -0.185116*sin(M)        -0.114332*sin(2*F)
   +0.058793*sin(2*D-2*Mp)+0.057066*sin(2*D-M-Mp) +0.053322*sin(2*D+Mp)
   +0.045758*sin(2*D-M)   -0.040923*sin(M-Mp)     -0.034720*sin(D)
   -0.030383*sin(M+Mp)    +0.015327*sin(2*D-2*F)  -0.012528*sin(Mp+2*F)
   +0.010980*sin(Mp-2*F)  +0.010675*sin(4*D-Mp)   +0.010034*sin(3*Mp);
  const b =
    5.128122*sin(F)       +0.280602*sin(Mp+F)     +0.277693*sin(Mp-F)
   +0.173237*sin(2*D-F)   +0.055413*sin(2*D-Mp+F) +0.046271*sin(2*D-Mp-F)
   +0.032573*sin(2*D+F)   +0.017198*sin(2*Mp+F)   +0.009266*sin(2*D+Mp-F);
  const dist = 385000.56 - 20905.355*cos(Mp) - 3699.111*cos(2*D-Mp)
             - 2955.968*cos(2*D) - 569.925*cos(2*Mp);
  return vec(norm(l), b, dist / AU);
}

function vec(lon, lat, r) {
  return { lon, lat, dist: r,
    x: r * cos(lat) * cos(lon), y: r * cos(lat) * sin(lon), z: r * sin(lat) };
}
