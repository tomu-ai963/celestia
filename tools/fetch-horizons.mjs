#!/usr/bin/env node
/**
 * fetch-horizons.mjs — JPL Horizons から検証用フィクスチャを取得する
 *
 *   node tools/fetch-horizons.mjs           # 全部（vectors + apparent + ut + equinox）
 *   node tools/fetch-horizons.mjs vectors   # tests/fixtures/horizons/vectors.csv
 *   node tools/fetch-horizons.mjs apparent  # tests/fixtures/horizons/apparent.csv
 *   node tools/fetch-horizons.mjs ut        # tests/fixtures/horizons/ut.csv
 *   node tools/fetch-horizons.mjs equinox   # tests/fixtures/horizons/equinox.csv
 *
 * テストは **必ずフィクスチャを読む**。ここで叩いた API の結果をCSVにしてコミットし、
 * ネットワークのない環境でも `npm test` が完結するようにしている。
 *
 * ■ 比較条件（ここを間違えると数十秒角ずれる）
 *
 * 観測地点  : 500@399 = 地心（Earth body center）。地表観測地にすると
 *             日周視差で月が最大 1° ずれる
 * 時系      : JD は **TDB**。Horizons の VECTORS は TDB が既定で、
 *             こちらのモデルの T も力学時系のつもりなので直接そろう
 *             （アプリが暦日→JDを作るところは UT なので、そこは別問題。README参照）
 * 位置の種別: VEC_CORR='LT' = astrometric（光行時間補正のみ）。
 *             既定の 'NONE' は幾何学的位置、'LT+S' は apparent（年周光行差込み）。
 *             こちらのモデルは光行時間だけ入れているので 'LT' が対応する
 * フレーム  : REF_PLANE='ECLIPTIC' + REF_SYSTEM='ICRF' = **J2000 の平均黄道**。
 *             Horizons のベクトル出力に of-date 黄道の選択肢はないので、
 *             ここは J2000 で取り、テスト側で src/precession.mjs を通して
 *             of-date に移してから比較する
 *
 * ■ of-date フレームそのものの検査は別口で
 * 上のやり方だと歳差を自前の実装で往復するので、フレームの取り違えは検出できない。
 * そこで apparent.csv（OBSERVER quantity 31 = ObsEcLon/Lat、視位置・**of-date**）を
 * 併せて取り、そちらとも突き合わせる。1.4° 級の取り違えは即座に落ちる。
 * equinox.csv は春分の瞬間を割り出すための素データ（tests/frame.test.mjs の出典）。
 *
 * ■ ΔT の検査だけは時刻を UT で指定する（ut.csv / P3.5）
 * 上の2つは TDB/TT で取っているので、こちらが ΔT を足そうが引こうが往復して打ち消え、
 * **ΔT の符号を取り違えても気づけない**。そこで ut.csv だけは時刻を暦日の UT で渡し、
 * アプリと同じ「UT を入れて位置を得る」経路まるごとを突き合わせる。
 * 2000年の月で 実測 5″（正しい向き）/ 32″（ΔT なし）/ 69″（符号が逆）と割れる。
 *
 * API: https://ssd-api.jpl.nasa.gov/doc/horizons.html
 */
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'tests', 'fixtures', 'horizons');
const API = 'https://ssd.jpl.nasa.gov/api/horizons.api';

/** Horizons の天体コード。太陽は 10、月は 301、惑星は重心ではなく本体を使う */
export const TARGETS = {
  sun: '10', moon: '301', mercury: '199', venus: '299', mars: '499',
  jupiter: '599', saturn: '699', uranus: '799', neptune: '899', pluto: '999'
};

/**
 * サンプル点: 各年 1月15日 12:00 TDB。
 * 1月1日にしないのは Horizons の海王星の解が 1800-Jan-02 始まりで、
 * 1800年の 1月1日が範囲外になるため（他の天体は 1月1日でも取れる）。
 */
export const EPOCHS = [1800, 1850, 1900, 1950, 2000, 2025, 2050]
  .map(y => ({ year: y, jd: jdTDB(y, 1, 15, 12) }));

function jdTDB(y, m, d, h) {
  let yy = y, mm = m;
  if (mm <= 2) { yy -= 1; mm += 12; }
  const A = Math.floor(yy / 100), B = 2 - A + Math.floor(A / 4);
  return Math.floor(365.25 * (yy + 4716)) + Math.floor(30.6001 * (mm + 1))
    + d + h / 24 + B - 1524.5;
}

async function api(params) {
  const q = Object.entries(params)
    .map(([k, v]) => `${k}=${encodeURIComponent(v)}`).join('&');
  const res = await fetch(`${API}?format=text&${q}`);
  if (!res.ok) throw new Error(`Horizons ${res.status} ${res.statusText}`);
  const text = await res.text();
  const body = text.split('$$SOE')[1]?.split('$$EOE')[0];
  if (!body) throw new Error(`$$SOE が見つからない:\n${text.slice(0, 1200)}`);
  return { body, text };
}

const sleep = ms => new Promise(r => setTimeout(r, ms));

/* ------------------------------------------------------------------
   1. astrometric ベクトル（J2000 黄道）
   ------------------------------------------------------------------ */
async function fetchVectors() {
  const rows = ['# JPL Horizons: astrometric geocentric vectors',
    '# CENTER=500@399 (geocentric) / REF_PLANE=ECLIPTIC + REF_SYSTEM=ICRF (mean ecliptic of J2000)',
    '# VEC_CORR=LT (astrometric: light-time only, no aberration) / OUT_UNITS=AU-D / times are TDB',
    '# generated by tools/fetch-horizons.mjs',
    'body,jd_tdb,x_au,y_au,z_au'];
  for (const [name, id] of Object.entries(TARGETS)) {
    for (const e of EPOCHS) {
      const { body } = await api({
        COMMAND: `'${id}'`, OBJ_DATA: "'NO'", MAKE_EPHEM: "'YES'",
        EPHEM_TYPE: "'VECTORS'", CENTER: "'500@399'",
        TLIST: `'${e.jd.toFixed(6)}'`, TLIST_TYPE: "'JD'",
        REF_PLANE: "'ECLIPTIC'", REF_SYSTEM: "'ICRF'",
        VEC_CORR: "'LT'", VEC_TABLE: "'1'", OUT_UNITS: "'AU-D'", CSV_FORMAT: "'YES'"
      });
      const [jd, , x, y, z] = body.trim().split(/\s*,\s*/);
      rows.push([name, (+jd).toFixed(6), x, y, z].join(','));
      process.stderr.write(`vectors ${name} ${e.year}\n`);
      await sleep(250);
    }
  }
  return rows.join('\n') + '\n';
}

/* ------------------------------------------------------------------
   2. apparent の of-date 黄経・黄緯（フレームの健全性チェック用）
   ------------------------------------------------------------------ */
async function fetchApparent() {
  const rows = ['# JPL Horizons: apparent observer ecliptic lon/lat (quantity 31)',
    '# CENTER=500@399 (geocentric) / ObsEcLon,ObsEcLat = ecliptic AND EQUINOX OF DATE, apparent',
    '# apparent = astrometric + annual aberration + nutation',
    '# TIME_TYPE=TT — OBSERVER 表は既定が UT で、UT のまま渡すと ΔT ぶん (2000年で 64秒)',
    '#   ずれた瞬間の値になる。月は 0.55″/秒 動くので 37″ の食い違いになり、',
    '#   フレームの検査より大きくなってしまう。TT なら vectors.csv の TDB と 2ms で一致する',
    '# generated by tools/fetch-horizons.mjs',
    'body,jd_tt,lon_deg,lat_deg'];
  for (const [name, id] of Object.entries(TARGETS)) {
    for (const e of EPOCHS) {
      const { body } = await api({
        COMMAND: `'${id}'`, OBJ_DATA: "'NO'", MAKE_EPHEM: "'YES'",
        EPHEM_TYPE: "'OBSERVER'", CENTER: "'500@399'",
        TLIST: `'${e.jd.toFixed(6)}'`, TLIST_TYPE: "'JD'", TIME_TYPE: "'TT'",
        QUANTITIES: "'31'", ANG_FORMAT: "'DEG'", CSV_FORMAT: "'YES'",
        TIME_DIGITS: "'SECONDS'"
      });
      const f = body.trim().split(/\s*,\s*/);
      rows.push([name, e.jd.toFixed(6), f[f.length - 3], f[f.length - 2]].join(','));
      process.stderr.write(`apparent ${name} ${e.year}\n`);
      await sleep(250);
    }
  }
  return rows.join('\n') + '\n';
}

/* ------------------------------------------------------------------
   3. UT で指定した時刻の apparent（ΔT の適用そのものの検査用）
   ------------------------------------------------------------------ */
async function fetchUt() {
  const rows = ['# JPL Horizons: apparent observer ecliptic lon/lat (quantity 31)',
    '# CENTER=500@399 (geocentric) / ObsEcLon,ObsEcLat = ecliptic AND EQUINOX OF DATE, apparent',
    '# **times are UT** — TIME_TYPE を渡さない既定。apparent.csv (TT) との違いはここだけ',
    '# これで初めて ΔT の適用の向きが検査できる（TT で取ると往復して打ち消えるため）',
    '# generated by tools/fetch-horizons.mjs',
    'body,year,ut_stamp,lon_deg,lat_deg'];
  // ΔT に敏感な順に3天体。月 0.55″/秒 / 水星 0.019″/秒 / 太陽 0.011″/秒
  for (const name of ['moon', 'mercury', 'sun']) {
    for (const e of EPOCHS) {
      const stamp = `${e.year}-Jan-15 12:00:00`;
      const { body } = await api({
        COMMAND: `'${TARGETS[name]}'`, OBJ_DATA: "'NO'", MAKE_EPHEM: "'YES'",
        EPHEM_TYPE: "'OBSERVER'", CENTER: "'500@399'",
        TLIST: `'${stamp}'`, QUANTITIES: "'31'", ANG_FORMAT: "'DEG'",
        CSV_FORMAT: "'YES'", TIME_DIGITS: "'SECONDS'"
      });
      const f = body.trim().split(/\s*,\s*/);
      rows.push([name, e.year, stamp, f[f.length - 3], f[f.length - 2]].join(','));
      process.stderr.write(`ut ${name} ${e.year}\n`);
      await sleep(250);
    }
  }
  return rows.join('\n') + '\n';
}

/* ------------------------------------------------------------------
   4. 春分の瞬間（tests/frame.test.mjs の EQUINOX の出典）
   ------------------------------------------------------------------ */
async function fetchEquinox() {
  const rows = ['# JPL Horizons: apparent solar ecliptic longitude around the March equinox',
    '# CENTER=500@399 / quantity 31 (ObsEcLon = of-date, apparent) / 10-minute steps / times are UT',
    '# 0° を跨ぐ2点を線形補間したものが tests/frame.test.mjs の EQUINOX',
    '# generated by tools/fetch-horizons.mjs',
    'year,t_before_ut,lon_before_deg,t_after_ut,lon_after_deg,interpolated_ut'];
  for (const e of EPOCHS) {
    const y = e.year;
    const { body } = await api({
      COMMAND: "'10'", OBJ_DATA: "'NO'", MAKE_EPHEM: "'YES'",
      EPHEM_TYPE: "'OBSERVER'", CENTER: "'500@399'",
      START_TIME: `'${y}-03-19'`, STOP_TIME: `'${y}-03-22'`, STEP_SIZE: "'10m'",
      QUANTITIES: "'31'", ANG_FORMAT: "'DEG'", CSV_FORMAT: "'YES'", TIME_DIGITS: "'SECONDS'"
    });
    let prev = null;
    for (const line of body.trim().split('\n')) {
      const f = line.split(/\s*,\s*/);
      const t = f[0].trim();
      let lon = parseFloat(f[f.length - 3]);
      if (!Number.isFinite(lon)) continue;
      if (lon > 180) lon -= 360;
      if (prev && prev.lon < 0 && lon >= 0) {
        const frac = -prev.lon / (lon - prev.lon);            // 0..1
        rows.push([y, prev.t, prev.lon.toFixed(7), t, lon.toFixed(7),
          addMinutes(prev.t, 10 * frac)].join(','));
        break;
      }
      prev = { t, lon };
    }
    process.stderr.write(`equinox ${y}\n`);
    await sleep(250);
  }
  return rows.join('\n') + '\n';
}

/** '1800-Mar-20 20:10:00' + 分 → 同形式（秒まで） */
function addMinutes(stamp, mins) {
  const MON = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
  const m = stamp.match(/(\d+)-(\w+)-(\d+)\s+(\d+):(\d+):(\d+)/);
  const [, Y, mon, D, h, mi, s] = m;
  let total = +h * 3600 + +mi * 60 + +s + Math.round(mins * 60);
  const dayShift = Math.floor(total / 86400); total -= dayShift * 86400;
  const p = n => String(n).padStart(2, '0');
  return `${Y}-${MON[MON.indexOf(mon)]}-${p(+D + dayShift)} `
    + `${p(Math.floor(total / 3600))}:${p(Math.floor(total / 60) % 60)}:${p(total % 60)}`;
}

/* ------------------------------------------------------------------ */
const JOBS = { vectors: fetchVectors, apparent: fetchApparent, ut: fetchUt, equinox: fetchEquinox };

const want = process.argv.slice(2).filter(a => a in JOBS);
const jobs = want.length ? want : Object.keys(JOBS);
await mkdir(OUT, { recursive: true });
for (const j of jobs) {
  const csv = await JOBS[j]();
  await writeFile(join(OUT, `${j}.csv`), csv);
  console.log(`wrote tests/fixtures/horizons/${j}.csv`);
}
